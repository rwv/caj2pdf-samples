"""Original C8 ornament controls and single-slot geometric font discriminators.

Resource aliases are measured metadata, not semantic Unicode or bundled fonts.
Only fonts generated by this project's geometric builder are edited.
"""

import argparse
import hashlib
import json
from pathlib import Path

from fontTools.ttLib import TTFont

from c8_geometric_font import font
from c8_style_fixture import document


ALIASES = {1: 23812, 2: 23813, 46: 23873, 117: 23957}


def control(value, *, legacy_neighbor=False):
    if value not in ALIASES:
        raise ValueError("unmeasured ornament value")
    words = []
    for y, length in [(4800, 500), (5200, 1000), (5600, 3000)]:
        words += [0x8010, value, 4900, y, 4900 + length, y]
    words += [0x8006, 0 if legacy_neighbor else 0xa383, 4900, 6300, 7900, 6300]
    return document([(0x10a5, 0, 6)], codes=(), run_words=words,
                    width=6400, height=4800)


def generate(output):
    output.mkdir(parents=True, exist_ok=False)
    base = output / "original-marker.ttf"
    font(base, "HGBZ_CNKI", narrow_decoration=True)
    rows = []
    for value, alias in ALIASES.items():
        data = control(value)
        source = output / f"ornament-{value}.caj"
        source.write_bytes(data)
        directory = output / f"marker-{value}"
        directory.mkdir()
        path = directory / "HGBZ_CNKI.ttf"
        with TTFont(base, recalcTimestamp=False) as generated:
            for table in generated["cmap"].tables:
                if table.isUnicode():
                    table.cmap.pop(23812, None)
                    table.cmap[alias] = "upper"
            generated.save(path)
        rows.append({"value": value, "alias": alias, "file": source.name,
                     "source_sha256": hashlib.sha256(data).hexdigest(),
                     "marker_file": str(path.relative_to(output)),
                     "marker_sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    (output / "manifest.json").write_text(json.dumps(rows, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="new external output directory")
    generate(parser.parse_args().output)
